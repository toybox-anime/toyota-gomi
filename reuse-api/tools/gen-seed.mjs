// 市データの初期投入SQLを作る（豊田市: data.js/config.js、知立市: demo-chiryu/data-chiryu.js）
//   node tools/gen-seed.mjs > seed.sql
//   npx wrangler d1 execute gomi-reuse --remote --file=seed.sql
// INSERT OR IGNORE なので、職員が画面で直した内容は上書きしない。
import fs from "node:fs";
import vm from "node:vm";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
function load(files, names) {
  const ctx = {};
  vm.createContext(ctx);
  const src = files.map(f => fs.readFileSync(path.join(root, f), "utf8")).join("\n") +
    `\n;globalThis.__out = { ${names.join(", ")} };`;
  vm.runInContext(src, ctx);
  return ctx.__out;
}
const q = s => "'" + String(s).replace(/'/g, "''") + "'";
const now = Date.now();
const out = ["-- generated by tools/gen-seed.mjs " + new Date().toISOString()];

function city(id, config, categories, districts) {
  out.push(`INSERT OR IGNORE INTO cities (id, config, categories, version, updated_at) VALUES (${q(id)}, ${q(JSON.stringify(config))}, ${q(JSON.stringify(categories))}, 1, ${now});`);
  districts.forEach((d, i) => {
    out.push(`INSERT OR IGNORE INTO districts (city, id, area, name, schedule, verified, sort, updated_at) VALUES (${q(id)}, ${q(d.id)}, ${q(d.area)}, ${q(d.name)}, ${q(JSON.stringify(d.schedule))}, ${d.verified ? 1 : 0}, ${i + 1}, ${now});`);
  });
}

// ---- 豊田市 ----
{
  const { CONFIG, I18N, CATEGORIES, DISTRICTS } = load(["config.js", "data.js"], ["CONFIG", "I18N", "CATEGORIES", "DISTRICTS"]);
  const cats = {};
  for (const [k, c] of Object.entries(CATEGORIES)) {
    cats[k] = { name: c.name, color: c.color, icon: c.icon,
      names: Object.fromEntries(["ja", "en", "pt", "easy"].map(l => [l, I18N[l].cats[k]])) };
  }
  city("toyota", {
    cityName: CONFIG.cityName, cityShort: CONFIG.cityShort, brandColor: CONFIG.brandColor, brandColorDark: CONFIG.brandColorDark,
    logo: "", officialUrl: CONFIG.officialUrl, dictUrl: CONFIG.dictUrl, dataUpdated: CONFIG.dataUpdated,
    collectTime: "08:30", sodaiUrl: "", sodaiPhone: "", sodaiNote: "",
  }, cats, DISTRICTS.map(d => ({ id: d.id, area: d.area, name: d.name, verified: d.verified !== false, schedule: d.schedule })));
}

// ---- 知立市（ゴミチェッカーの公式文言。日付を計算できるのは「毎週」の可燃ごみだけ。残りは文言で表示）----
{
  const { CHIRYU } = load(["demo-chiryu/data-chiryu.js"], ["CHIRYU"]);
  const ROWS = [["あ行", "あいうえお"], ["か行", "かきくけこがぎぐげご"], ["さ行", "さしすせそざじずぜぞ"], ["た行", "たちつてとだぢづでど"],
    ["な行", "なにぬねの"], ["は行", "はひふへほばびぶべぼぱぴぷぺぽ"], ["ま行", "まみむめも"], ["や行", "やゆよ"], ["ら行", "らりるれろ"], ["わ行", "わをん"]];
  const rowOf = y => (ROWS.find(([, cs]) => cs.includes((y || "")[0])) || ["その他"])[0];
  const cats = {
    kanen:  { name: "可燃ごみ", color: "#d9412b", icon: "🔥", names: { ja: "可燃ごみ", en: "Burnable", pt: "Queimável", easy: "もえる ごみ" } },
    pura:   { name: "プラスチック資源", color: "#e3a008", icon: "♳", names: { ja: "プラスチック資源", en: "Plastics", pt: "Plásticos", easy: "プラスチック" } },
    funen:  { name: "不燃物", color: "#5b6673", icon: "🪨", names: { ja: "不燃物", en: "Non-burnable", pt: "Não queimável", easy: "もえない ごみ" } },
    shigen: { name: "資源物", color: "#2e6fd6", icon: "♻️", names: { ja: "資源物", en: "Recyclables", pt: "Recicláveis", easy: "しげん" } },
  };
  city("chiryu", {
    cityName: "愛知県知立市", cityShort: "知立市", brandColor: "#6a4c9c", brandColorDark: "#513a78",
    logo: "", officialUrl: "https://www.city.chiryu.aichi.jp/", dictUrl: "", dataUpdated: "ゴミチェッカーより",
    collectTime: "08:30", sodaiUrl: "", sodaiPhone: "", sodaiNote: "",
  }, cats, CHIRYU.map(d => {
    const schedule = {};
    for (const [k, v] of Object.entries(d.cats)) {
      schedule[k] = v.weekly && k === "kanen" ? { weekly: v.days } : { text: v.text };
    }
    return { id: d.id, area: rowOf(d.yomi), name: d.name, verified: false, schedule };
  }));
}

process.stdout.write(out.join("\n") + "\n");
